# WpsExcelAI Windows 安装脚本
# 用法（PowerShell）：
#   Set-ExecutionPolicy -Scope Process Bypass
#   .\install-windows.ps1
# 或双击 install.bat
#
# 会：
# 1) 复制 addon → %APPDATA%\kingsoft\wps\jsaddons\WpsExcelAI_1.0.0
# 2) 写入/合并 publish.xml（file 模式）
# 3) 复制运行时到 %APPDATA%\WpsExcelAI\（静态 :13991 + 代理 :8787）
# 4) 注册当前用户登录计划任务启动服务（需要 python，或提示手动）

$ErrorActionPreference = "Stop"
# Support both repo layout (install/) and dist layout (script next to addon/)
if (Test-Path (Join-Path $PSScriptRoot "addon\ribbon.xml")) {
  $Root = $PSScriptRoot
} else {
  $Root = Split-Path -Parent $PSScriptRoot
}
$AddonSrc = Join-Path $Root "addon"
$ProxySrc = Join-Path $Root "proxy\server.py"
$ServerSrc = Join-Path $Root "scripts\addon-server.py"
if (-not (Test-Path $ServerSrc)) { $ServerSrc = Join-Path $Root "addon-server.py" }
$PublishSrc = Join-Path $PSScriptRoot "publish.xml"
if (-not (Test-Path $PublishSrc)) {
  $PublishSrc = Join-Path $Root "install\publish.xml"
}

$DestRoot = Join-Path $env:APPDATA "kingsoft\wps\jsaddons"
$DestAddon = Join-Path $DestRoot "WpsExcelAI_1.0.0"
$Support = Join-Path $env:APPDATA "WpsExcelAI"
$SupportAddon = Join-Path $Support "addon"
$Port = 13991
$ProxyPort = 8787

function Find-Python {
  $candidates = @(
    (Get-Command python -ErrorAction SilentlyContinue | Select-Object -ExpandProperty Source -ErrorAction SilentlyContinue),
    (Get-Command python3 -ErrorAction SilentlyContinue | Select-Object -ExpandProperty Source -ErrorAction SilentlyContinue),
    "$env:LOCALAPPDATA\Programs\Python\Python312\python.exe",
    "$env:LOCALAPPDATA\Programs\Python\Python311\python.exe",
    "C:\Python312\python.exe",
    "C:\Python311\python.exe"
  ) | Where-Object { $_ -and (Test-Path $_) }
  foreach ($c in $candidates) {
    try {
      & $c -c "import http.server, urllib.request" 2>$null
      if ($LASTEXITCODE -eq 0 -or $?) { return $c }
    } catch {}
  }
  return $null
}

if (-not (Test-Path $AddonSrc)) { throw "找不到 addon 目录: $AddonSrc" }
if (-not (Test-Path $ProxySrc)) { throw "找不到 proxy\server.py: $ProxySrc" }

Write-Host "==> 复制加载项 → $DestAddon"
New-Item -ItemType Directory -Force -Path $DestRoot | Out-Null
if (Test-Path $DestAddon) { Remove-Item -Recurse -Force $DestAddon }
Copy-Item -Recurse -Force $AddonSrc $DestAddon

# index.html for safety
$idx = Join-Path $DestAddon "index.html"
if (-not (Test-Path $idx)) {
  @"
<!DOCTYPE html>
<html><head><meta charset="UTF-8"/><title>WpsExcelAI</title>
<script type="text/javascript" src="./main.js"></script>
</head><body></body></html>
"@ | Set-Content -Path $idx -Encoding UTF8
}

$PublishDest = Join-Path $DestRoot "publish.xml"
$PluginLine = '<jsplugin name="WpsExcelAI" type="et" version="1.0.0" url="file://" enable="enable_dev" />'
if (-not (Test-Path $PublishDest)) {
  if (Test-Path $PublishSrc) {
    Copy-Item -Force $PublishSrc $PublishDest
  } else {
    @"
<?xml version="1.0" encoding="UTF-8"?>
<jsplugins>
  $PluginLine
</jsplugins>
"@ | Set-Content -Path $PublishDest -Encoding UTF8
  }
  Write-Host "已写入 publish.xml"
} else {
  $content = Get-Content -Raw -Encoding UTF8 $PublishDest
  if ($content -notmatch 'name\s*=\s*"WpsExcelAI"') {
    if ($content -match '</jsplugins>') {
      $content = $content -replace '</jsplugins>', ("  " + $PluginLine + "`r`n</jsplugins>")
      Set-Content -Path $PublishDest -Value $content -Encoding UTF8
      Write-Host "已向现有 publish.xml 追加 WpsExcelAI"
    } else {
      Write-Host "警告: publish.xml 格式异常，请手动合并。参考: $PublishSrc"
    }
  } else {
    Write-Host "publish.xml 中已存在 WpsExcelAI 条目"
  }
}

Write-Host "==> 运行时 → $Support"
# 不删除 $Support\settings.json（API 配置持久化）
New-Item -ItemType Directory -Force -Path $Support, $SupportAddon, (Join-Path $Support "logs") | Out-Null
Copy-Item -Recurse -Force "$AddonSrc\*" $SupportAddon
Copy-Item -Force $ProxySrc (Join-Path $Support "proxy-server.py")
if (-not (Test-Path $ServerSrc)) { throw "找不到 addon-server.py: $ServerSrc" }
Copy-Item -Force $ServerSrc (Join-Path $Support "addon-server.py")
Write-Host "settings.json 路径: $(Join-Path $Support 'settings.json')（安装不会删除）"

$Python = Find-Python
$StartPs1 = Join-Path $Support "start-services.ps1"
@"
# Auto-generated by WpsExcelAI installer — starts static :$Port and proxy :$ProxyPort
`$ErrorActionPreference = 'SilentlyContinue'
`$Support = '$Support'
`$Addon = '$SupportAddon'
`$Python = '$Python'
`$Log = Join-Path `$Support 'logs'
New-Item -ItemType Directory -Force -Path `$Log | Out-Null

function Stop-Port(`$p) {
  Get-NetTCPConnection -LocalPort `$p -State Listen -ErrorAction SilentlyContinue |
    ForEach-Object { Stop-Process -Id `$_.OwningProcess -Force -ErrorAction SilentlyContinue }
}

if (-not `$Python -or -not (Test-Path `$Python)) {
  Add-Content (Join-Path `$Log 'error.log') ("[" + (Get-Date) + "] python not found")
  exit 1
}

Stop-Port $Port
Stop-Port $ProxyPort
Start-Sleep -Milliseconds 400

`$env:WPS_EXCELAI_SERVE_DIR = `$Addon
`$env:WPS_EXCELAI_PORT = '$Port'
Start-Process -WindowStyle Hidden -FilePath `$Python -ArgumentList @((Join-Path `$Support 'addon-server.py'), `$Addon) -WorkingDirectory `$Support `
  -RedirectStandardOutput (Join-Path `$Log 'server.out.log') -RedirectStandardError (Join-Path `$Log 'server.err.log')
Start-Process -WindowStyle Hidden -FilePath `$Python -ArgumentList @((Join-Path `$Support 'proxy-server.py')) -WorkingDirectory `$Support `
  -RedirectStandardOutput (Join-Path `$Log 'proxy.out.log') -RedirectStandardError (Join-Path `$Log 'proxy.err.log')
"@ | Set-Content -Path $StartPs1 -Encoding UTF8

if ($Python) {
  Write-Host "找到 Python: $Python"
  Write-Host "==> 注册登录计划任务 WpsExcelAI.Services"
  $taskName = "WpsExcelAI.Services"
  Unregister-ScheduledTask -TaskName $taskName -Confirm:$false -ErrorAction SilentlyContinue
  $action = New-ScheduledTaskAction -Execute "powershell.exe" -Argument "-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$StartPs1`""
  $trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
  $settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable
  Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Settings $settings -Description "WPS Excel AI 助手 静态服务与 CORS 代理" | Out-Null
  Write-Host "==> 立即启动服务"
  & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $StartPs1
  Start-Sleep -Seconds 1
  try {
    $r = Invoke-WebRequest -Uri "http://127.0.0.1:$Port/ribbon.xml" -UseBasicParsing -TimeoutSec 3
    Write-Host "OK static ribbon HTTP $($r.StatusCode)"
  } catch {
    Write-Host "WARN: 静态服务检查失败 — 可手动运行 $StartPs1"
  }
  try {
    $h = Invoke-WebRequest -Uri "http://127.0.0.1:$ProxyPort/health" -UseBasicParsing -TimeoutSec 3
    Write-Host "OK proxy health $($h.Content)"
  } catch {
    Write-Host "WARN: 代理检查失败 — 可手动运行 $StartPs1"
  }
} else {
  Write-Host ""
  Write-Host "未检测到 Python。加载项文件已复制，但本地 HTTP/代理未启动。"
  Write-Host "请安装 Python 3（勾选 Add to PATH），然后重新运行本脚本；"
  Write-Host "或手动：python "$(Join-Path $Support 'addon-server.py')" "$SupportAddon""
  Write-Host "以及：python `"$(Join-Path $Support 'proxy-server.py')`""
  Write-Host "Windows file 模式多数情况下可不启静态站也能加载插件；但「使用本地代理」仍需要 Python 跑代理。"
}

Write-Host ""
Write-Host "安装完成。请完全退出并重启 WPS 表格，打开「AI 助手」。"
Write-Host "验证：浏览器打开 http://127.0.0.1:$ProxyPort/health （若启用了代理）"
Write-Host "设置页填写 API Key，建议勾选本地代理。"
